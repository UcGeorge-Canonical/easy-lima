#!/usr/bin/env python3
"""Produce the notices shipped with binaries from the resolved Go modules."""
import json
import os
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def main():
    modules_by_path = {}
    decoder = json.JSONDecoder()
    # Include modules linked on either supported OS, not dependencies of
    # dependency tests or maintainer tools that are absent from the binary.
    for platform in ("darwin", "linux"):
        raw = subprocess.check_output([os.environ.get("GO", "go"), "list", "-deps", "-json", "./cmd/easy-lima"], cwd=ROOT, env=dict(os.environ, GOOS=platform, CGO_ENABLED="0")).decode()
        while raw.strip():
            item, end = decoder.raw_decode(raw.lstrip())
            raw = raw.lstrip()[end:]
            module = item.get("Module")
            if module and not module.get("Main"):
                modules_by_path[module["Path"]] = module
    modules = list(modules_by_path.values())
    lines = ["Third-party licenses for easy-lima\n", "Generated by scripts/licenses.py from go.mod and go.sum.\n"]
    goroot = Path(subprocess.check_output([os.environ.get("GO", "go"), "env", "GOROOT"]).decode().strip())
    # Homebrew keeps the license beside libexec; downloaded Go toolchains
    # and upstream distributions keep it directly in GOROOT.
    go_license = next((p for p in (goroot / "LICENSE", goroot.parent / "LICENSE") if p.is_file()), None)
    if go_license is None:
        raise RuntimeError("Missing Go standard library license in " + str(goroot))
    lines += ["\n=== Go standard library ===\n", go_license.read_text()]
    for item in sorted(modules, key=lambda value: value["Path"]):
        if not item.get("Dir"):
            raise RuntimeError("Download module before collecting its license: " + item["Path"])
        directory = Path(item["Dir"])
        files = sorted(p for p in directory.iterdir() if p.is_file() and p.name.upper().startswith(("LICENSE", "COPYING", "NOTICE")))
        if not files:
            raise RuntimeError("Missing dependency license: " + item["Path"])
        lines.append("\n=== " + item["Path"] + " " + item["Version"] + " ===\n")
        for path in files:
            lines.extend(["\n" + path.name + "\n", path.read_text()])
    (ROOT / "THIRD_PARTY_NOTICES.txt").write_text("".join(lines))


if __name__ == "__main__":
    main()
